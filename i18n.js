// Global i18n Controller
class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem('enipay_lang') || 'zh';
    if (!translations[this.currentLang]) this.currentLang = 'zh';
  }

  init() {
    this.applyLanguage(this.currentLang);
  }

  setLanguage(lang) {
    if (!translations[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('enipay_lang', lang);
    this.applyLanguage(lang);
  }

  applyLanguage(lang) {
    const dict = translations[lang] || translations.zh;

    // Update all elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.innerHTML = dict[key];
      }
    });

    // Update active state in language selectors
    document.querySelectorAll('.lang-select-option').forEach(opt => {
      if (opt.getAttribute('data-lang') === lang) {
        opt.classList.add('active-lang');
      } else {
        opt.classList.remove('active-lang');
      }
    });

    // Update lang label on top bar
    const currentLangLabel = document.getElementById('current-lang-text');
    if (currentLangLabel) {
      currentLangLabel.innerText = dict.lang_name;
    }

    // Trigger audio chime
    if (window.audio && !window.audio.muted) {
      window.audio.playChime();
    }
  }
}

const i18n = new I18nManager();
window.i18n = i18n;
window.setAppLanguage = function(lang) {
  i18n.setLanguage(lang);
};
